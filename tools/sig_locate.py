"""Locate the plugin's hardcoded addresses inside a DIFFERENT build of AC4BFSP.exe.

Method: take the bytes at each known-build address, then search the target build for the same
bytes. Start with a long window and shorten it until the signature is (a) found and (b) unique.
The result is a known->target address map plus a per-site confidence.

    python sig_locate.py --target "D:\\Games\\...\\AC4BFSP.exe" [--emit header.h]

Known build: D:\\SteamLibrary\\...\\Assassin's Creed IV Black Flag\\AC4BFSP.exe  (45,056,040 B)
"""
import re
import os
import sys
import json
import glob

KNOWN = r"D:\SteamLibrary\steamapps\common\Assassin's Creed IV Black Flag\AC4BFSP.exe"
SRC = r"C:\Users\Administrator\Documents\Default Project\projects\assassins-creed\bf-coop\ref\AC4Coop\src"
IMAGE_BASE = 0x400000
WINDOWS = [48, 40, 32, 24, 20, 16, 12]
MASK = 0x400000          # 45,056,040 = known exe size


def collect_addrs():
    """Every absolute code address the plugin uses, from the source."""
    pats = [
        re.compile(r'base\(\)\s*\+\s*0x([0-9A-Fa-f]+)'),
        re.compile(r'\([^()]{0,80}?\)\s*0x([0-9A-Fa-f]{6,8})\b'),
        re.compile(r'\b0x([0-9A-Fa-f]{6,8})\b'),
    ]
    found = {}
    for path in glob.glob(os.path.join(SRC, "*.cpp")) + glob.glob(os.path.join(SRC, "*.h")):
        try:
            text = open(path, encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        for p in pats:
            for m in p.finditer(text):
                v = int(m.group(1), 16)
                if not (0x10000 <= v < 0x2000000):
                    continue
                # keep only things that look like an RVA or a VA inside the image
                if v < IMAGE_BASE:
                    v += IMAGE_BASE
                if not (IMAGE_BASE <= v < IMAGE_BASE + MASK):
                    continue
                line = text[:m.start()].count("\n") + 1
                found.setdefault(v, (os.path.basename(path), line))
    return found


def load(path):
    with open(path, "rb") as f:
        return f.read()


def find_all(hay, needle, limit=8):
    out = []
    start = 0
    while True:
        i = hay.find(needle, start)
        if i < 0:
            break
        out.append(i)
        start = i + 1
        if len(out) >= limit:
            break
    return out


def main(argv):
    target = None
    emit = None
    for i, a in enumerate(argv):
        if a == "--target" and i + 1 < len(argv):
            target = argv[i + 1]
        if a == "--emit" and i + 1 < len(argv):
            emit = argv[i + 1]
    if not target:
        print(__doc__)
        return 2

    known = load(KNOWN)
    tgt = load(target)
    print(f"known : {len(known)} B   target: {len(tgt)} B")
    addrs = sorted(collect_addrs())
    print(f"candidate addresses in source: {len(addrs)}")

    rows = []
    for va in addrs:
        off = va - IMAGE_BASE
        if off + 8 >= len(known):
            continue
        hit = None
        for w in WINDOWS:
            if off + w > len(known):
                continue
            needle = known[off:off + w]
            positions = find_all(tgt, needle)
            if len(positions) == 1:
                hit = (w, positions[0] + IMAGE_BASE)
                break
            if len(positions) > 1:
                hit = (w, positions[0] + IMAGE_BASE, len(positions))
                break
        if hit:
            rows.append({"known": va, "sig_len": hit[0], "target": hit[1],
                         "ambiguous": len(hit) > 2, "n": hit[2] if len(hit) > 2 else 1})
        else:
            rows.append({"known": va, "sig_len": 0, "target": None, "ambiguous": False, "n": 0})

    found = [r for r in rows if r["target"]]
    uniq = [r for r in rows if r["target"] and not r["ambiguous"]]
    print(f"located: {len(found)}/{len(rows)}   unique: {len(uniq)}")
    print(f"{'known':>10} {'target':>10} {'sig':>4}  n")
    for r in rows:
        t = f"{r['target']:#x}" if r["target"] else "NOT FOUND"
        print(f"{r['known']:#10x} {t:>10} {r['sig_len']:4}  {r['n']}")

    out = r"C:\Users\Administrator\Documents\Default Project\projects\assassins-creed\bf-coop\ops\evidence\sig_map.json"
    with open(out, "w", encoding="utf-8") as f:
        json.dump({"known_exe": KNOWN, "target_exe": target, "rows": rows}, f, indent=1)
    print("map ->", out)

    if emit:
        with open(emit, "w", encoding="utf-8") as f:
            f.write("// generated by ops/tools/sig_locate.py - known build -> current build\n")
            f.write("#pragma once\n#include <stdint.h>\n")
            f.write("struct SigEntry { uint32_t knownRva; uint32_t targetRva; uint8_t sigLen; uint8_t ambiguous; };\n")
            f.write("static const SigEntry kSigMap[] = {\n")
            for r in rows:
                if not r["target"]:
                    continue
                k = r["known"] - IMAGE_BASE
                t = r["target"] - IMAGE_BASE
                f.write(f"  {{ 0x{k:08X}, 0x{t:08X}, {r['sig_len']}, {1 if r['ambiguous'] else 0} }},\n")
            f.write("};\n")
            f.write(f"static const int kSigMapN = {len(uniq)};\n")
        print("header ->", emit)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
