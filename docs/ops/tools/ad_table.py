#!/usr/bin/env python3
"""Turn `[AD]` capture lines into the killer-action -> victim-clip table (A1).

The game logs, once per local death:

    [AD] player=18981193 victim=18981194 objId=4026538708 dist=4.2 ent=401D1820

`player` is the attacker's action alias at the kill; `victim` is the last alias
the engine played on the victim before it died. That pair is the mapping we need
so a replicated kill stops using one hardcoded clip.

    python ops/tools/ad_table.py                 # newest log
    python ops/tools/ad_table.py logA logB ...   # several captures
    python ops/tools/ad_table.py --emit death_clips.h
    python ops/tools/ad_table.py --selftest

Rule for the table: for each player alias, take the modal victim alias; if the
votes are split, emit the modal one and list the runners-up in a comment. A pair
seen once is emitted but marked `// seen 1x`.
"""
from __future__ import annotations

import argparse
import collections
import glob
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

GAME = r"D:\SteamLibrary\steamapps\common\Assassin's Creed IV Black Flag"
AD = re.compile(r"\[AD\]\s+(?:vanished\s+)?player=(\d+)\s+victim=(\d+)\s+objId=(\d+)\s+dist=([\d.]+)")
MARKERS = {
    "stealth_low": "low-profile kill from behind (walk)",
    "stealth_high": "high-profile assassination (standing / run-up)",
    "air": "air assassination",
    "ledge": "ledge assassination",
    "corner": "corner / cover assassination",
    "finisher": "combat finisher",
    "ground": "ground finisher",
    "pistol": "pistol shot",
    "blowpipe": "blowpipe / rope dart",
    "other": "anything else",
}


def parse(paths):
    rows = []
    for p in paths:
        try:
            for line in open(p, encoding="utf-8", errors="replace"):
                m = AD.search(line)
                if m:
                    rows.append({
                        "player": int(m.group(1)),
                        "victim": int(m.group(2)),
                        "objId": m.group(3),
                        "dist": float(m.group(4)),
                        "log": os.path.basename(p),
                    })
        except OSError:
            continue
    return rows


def newest_logs(n=3):
    logs = sorted(glob.glob(os.path.join(GAME, "phase1_log_*.txt")),
                  key=os.path.getmtime, reverse=True)
    return logs[:n]


def summarise(rows, max_dist=None):
    if max_dist is not None:
        far = [r for r in rows if r["dist"] > max_dist]
        rows = [r for r in rows if r["dist"] <= max_dist]
        if far:
            print(f"dropped {len(far)} line(s) beyond {max_dist} m "
                  f"(radius departures, not kills; see NET's note on the A1(b) gate)")
    zero = [r for r in rows if r["victim"] == 0]
    real = [r for r in rows if r["victim"] != 0]
    by_player = collections.defaultdict(collections.Counter)
    for r in real:
        by_player[r["player"]][r["victim"]] += 1

    print(f"[AD] lines: {len(rows)}   with a captured victim: {len(real)}   victim=0: {len(zero)}")
    if not rows:
        print("no [AD] lines — is [Coop] ActionDeathLog=1 and did anyone die locally?")
        return {}

    table = {}
    print(f"\n{'player alias':>14}  {'victim alias':>14}  {'votes':>5}  other candidates")
    for player, counter in sorted(by_player.items(), key=lambda kv: -sum(kv[1].values())):
        victim, votes = counter.most_common(1)[0]
        others = ", ".join(f"{v}x{n}" for v, n in counter.most_common()[1:]) or "-"
        table[player] = (victim, votes, dict(counter))
        print(f"{player:>14}  {victim:>14}  {votes:>5}  {others}")

    if zero:
        print(f"\n{len(zero)} kill(s) had no captured victim (victim=0): the victim died before any "
              f"capture saw it play a clip. Not an error; those pairs are simply unknown.")
    return table


def emit(table, path):
    lines = [
        "// Generated by ops/tools/ad_table.py from [AD] capture lines. Do not edit by hand.",
        "// killer action alias -> victim death clip, captured from the engine's own kills.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "struct DeathClipPair { uint32_t playerAlias; uint32_t victimClip; };",
        "",
        "// The clip the project used for every death before this table existed.",
        "static const uint32_t DEATH_CLIP_DEFAULT = 1818493434u;",
        "",
        "static const DeathClipPair kDeathClips[] = {",
    ]
    for player, (victim, votes, all_votes) in sorted(table.items()):
        note = f"// seen {votes}x"
        if len(all_votes) > 1:
            note += "  (split votes: " + ", ".join(f"{v}:{n}" for v, n in all_votes.items()) + ")"
        lines.append(f"    {{ 0x{player:08X}u, 0x{victim:08X}u }},  {note}")
    lines += [
        "};",
        "static const int kDeathClipCount = (int)(sizeof(kDeathClips) / sizeof(kDeathClips[0]));",
        "",
        "inline uint32_t DeathClipFor(uint32_t playerAlias) {",
        "    for (int i = 0; i < kDeathClipCount; ++i)",
        "        if (kDeathClips[i].playerAlias == playerAlias) return kDeathClips[i].victimClip;",
        "    return DEATH_CLIP_DEFAULT;",
        "}",
        "",
    ]
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(f"\nwrote {path}  ({len(table)} pair(s))")


def selftest():
    sample = [
        "[AD] player=111 victim=222 objId=4026538708 dist=4.2 ent=401D1820",
        "[AD] player=111 victim=222 objId=4026538711 dist=3.1 ent=407D4EE0",
        "[AD] player=111 victim=999 objId=4026538273 dist=2.0 ent=3FEC9140",
        "[AD] player=333 victim=0 objId=4026538708 dist=1.0 ent=401D1820",
    ]
    tmp = os.path.join(os.environ.get("TEMP", "."), "ad_selftest.log")
    open(tmp, "w", encoding="utf-8").write("\n".join(sample))
    rows = parse([tmp])
    assert len(rows) == 4, rows
    table = summarise(rows)
    assert table[111][0] == 222, table          # modal victim wins
    assert table[111][1] == 2, table            # two votes
    assert 333 not in table, table              # victim=0 excluded
    out = tmp + ".h"
    emit(table, out)
    txt = open(out, encoding="utf-8").read()
    assert "0x0000006F" in txt, txt             # 111
    assert "0x000000DE" in txt, txt             # 222
    os.remove(tmp)
    os.remove(out)
    print("\nSELFTEST PASS: parse, modal vote, victim=0 exclusion, header emit")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("logs", nargs="*")
    ap.add_argument("--emit", default="")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--max-dist", dest="max_dist", type=float, default=8.0,
                    help="ignore [AD] lines farther than this (default 8 m; real victims read <5 m)")
    args = ap.parse_args(argv)

    if args.selftest:
        selftest()
        return 0

    paths = args.logs or newest_logs()
    if not paths:
        sys.exit("no logs found")
    print("logs: " + ", ".join(os.path.basename(p) for p in paths))
    table = summarise(parse(paths), max_dist=args.max_dist)
    if args.emit and table:
        emit(table, args.emit)
    if table and len(table) < 3:
        print(f"\nNOTE: only {len(table)} distinct killer action(s). The A1 acceptance wants >= 3, "
              f"so the capture run should include more kill types.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
